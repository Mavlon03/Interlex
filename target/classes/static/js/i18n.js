// Language management
class I18n {
    constructor() {
        this.currentLang = this.getStoredLanguage() || 'uz';
        this.init();
    }

    getStoredLanguage() {
        return localStorage.getItem('language');
    }

    setStoredLanguage(lang) {
        localStorage.setItem('language', lang);
    }

    init() {
        this.updateLanguage(this.currentLang);
        this.bindLanguageSelectors();
    }

    bindLanguageSelectors() {
        const langLinks = document.querySelectorAll('[data-lang]');
        langLinks.forEach(link => {
            link.addEventListener('click', (e) => {
                e.preventDefault();
                const lang = e.target.getAttribute('data-lang');
                this.changeLanguage(lang);
            });
        });
    }

    changeLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            this.setStoredLanguage(lang);
            this.updateLanguage(lang);
            this.updateLanguageSelector(lang);

            // Update document language
            document.documentElement.lang = lang;

            // Trigger custom event for other components
            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
        }
    }

    updateLanguage(lang) {
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                element.textContent = translations[lang][key];
            }
        });

        // Update placeholders
        const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
        placeholderElements.forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (translations[lang] && translations[lang][key]) {
                element.placeholder = translations[lang][key];
            }
        });

        // Update titles
        const titleElements = document.querySelectorAll('[data-i18n-title]');
        titleElements.forEach(element => {
            const key = element.getAttribute('data-i18n-title');
            if (translations[lang] && translations[lang][key]) {
                element.title = translations[lang][key];
            }
        });

        // Update meta tags
        this.updateMetaTags(lang);
    }

    updateMetaTags(lang) {
        // Update page title
        const titleElement = document.querySelector('title[data-i18n]');
        if (titleElement) {
            const key = titleElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                titleElement.textContent = translations[lang][key];
            }
        }

        // Update meta description
        const descElement = document.querySelector('meta[name="description"][data-i18n]');
        if (descElement) {
            const key = descElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                descElement.content = translations[lang][key];
            }
        }

        // Update Open Graph tags
        const ogTitleElement = document.querySelector('meta[property="og:title"][data-i18n]');
        if (ogTitleElement) {
            const key = ogTitleElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                ogTitleElement.content = translations[lang][key];
            }
        }

        const ogDescElement = document.querySelector('meta[property="og:description"][data-i18n]');
        if (ogDescElement) {
            const key = ogDescElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                ogDescElement.content = translations[lang][key];
            }
        }

        // Update Twitter tags
        const twitterTitleElement = document.querySelector('meta[property="twitter:title"][data-i18n]');
        if (twitterTitleElement) {
            const key = twitterTitleElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                twitterTitleElement.content = translations[lang][key];
            }
        }

        const twitterDescElement = document.querySelector('meta[property="twitter:description"][data-i18n]');
        if (twitterDescElement) {
            const key = twitterDescElement.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                twitterDescElement.content = translations[lang][key];
            }
        }
    }

    updateLanguageSelector(lang) {
        const selector = document.getElementById('currentLangSelector');
        if (selector) {
            const langMap = {
                'uz': '🇺🇿 УЗ',
                'ru': '🇷🇺 РУ',
                'en': '🇬🇧 EN'
            };
            selector.textContent = langMap[lang] || langMap['uz'];
        }
    }

    getCurrentLanguage() {
        return this.currentLang;
    }

    translate(key) {
        return translations[this.currentLang] && translations[this.currentLang][key]
            ? translations[this.currentLang][key]
            : key;
    }
}

// Initialize i18n when DOM is loaded
let i18n;
document.addEventListener('DOMContentLoaded', () => {
    i18n = new I18n();
});

// Export for use in other scripts
window.I18n = I18n;
window.i18n = i18n;